"""Generate a complete Web, PWA, and OpenGraph icon bundle from a single source image.

Produces `favicon.ico` (7-tier), `favicon-16x16.png`, `favicon-32x32.png`, `favicon-48x48.png`,
`apple-touch-icon.png` (180x180), `icon-192x192.png`, `icon-512x512.png`, `og-image.png`
(1200x630), `site.webmanifest`, and `head-tags.html` in the target directory.

Prerequisites: Python 3.9+, Pillow (`pip install Pillow`).
Platform: Cross-platform.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from PIL import Image, ImageColor, ImageOps

sys.path.insert(0, str(Path(__file__).resolve().parent / "Common"))
from image_deps import DEFAULT_ICO_SIZES, load_image_any, normalize_help_argv  # noqa: E402

PNG_TIERS = {
    "favicon-16x16.png": (16, 16),
    "favicon-32x32.png": (32, 32),
    "favicon-48x48.png": (48, 48),
    "apple-touch-icon.png": (180, 180),
    "icon-192x192.png": (192, 192),
    "icon-512x512.png": (512, 512),
}

EPILOG = """\
Examples:
  new-web-icon-bundle.py logo.svg
      Generate all favicon, PWA, and OpenGraph assets in ./web-icons.

  new-web-icon-bundle.py KIP-PROFILE.jpg -o ./public/icons --app-name "QODE Fleet" --og-bg "#0F172A"
      Generate a full web icon suite with custom PWA manifest name and OpenGraph card background.
"""


def generate_web_bundle(
    input_path: Path,
    output_dir: Path,
    app_name: str = "Web App",
    og_bg: str = "#0F172A",
) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    img = load_image_any(input_path, svg_size=1024)
    created = {}

    with img:
        rgba = img.convert("RGBA")

        ico_path = output_dir / "favicon.ico"
        ico_master = ImageOps.pad(rgba, (256, 256), method=Image.Resampling.LANCZOS, color=(0, 0, 0, 0))
        ico_master.save(ico_path, format="ICO", sizes=DEFAULT_ICO_SIZES)
        created["favicon.ico"] = str(ico_path)

        for filename, dims in PNG_TIERS.items():
            target_path = output_dir / filename
            framed = ImageOps.pad(rgba, dims, method=Image.Resampling.LANCZOS, color=(0, 0, 0, 0))
            framed.save(target_path, format="PNG", optimize=True)
            created[filename] = str(target_path)

        og_path = output_dir / "og-image.png"
        try:
            rgb_bg = ImageColor.getrgb(og_bg)[:3]
        except Exception:
            rgb_bg = (15, 23, 42)
        og_canvas = Image.new("RGBA", (1200, 630), (*rgb_bg, 255))
        logo_fitted = ImageOps.pad(rgba, (440, 440), method=Image.Resampling.LANCZOS, color=(0, 0, 0, 0))
        og_canvas.paste(logo_fitted, ((1200 - 440) // 2, (630 - 440) // 2), mask=logo_fitted.split()[3])
        og_canvas.convert("RGB").save(og_path, format="PNG", optimize=True)
        created["og-image.png"] = str(og_path)

    manifest = {
        "name": app_name,
        "short_name": app_name,
        "icons": [
            {"src": "/icon-192x192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "/icon-512x512.png", "sizes": "512x512", "type": "image/png"},
        ],
        "theme_color": og_bg,
        "background_color": og_bg,
        "display": "standalone",
    }
    manifest_path = output_dir / "site.webmanifest"
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    created["site.webmanifest"] = str(manifest_path)

    html_snippet = """<!-- Generated by convert-image (new-web-icon-bundle.py) -->
<link rel="icon" type="image/x-icon" href="/favicon.ico">
<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32x32.png">
<link rel="icon" type="image/png" sizes="16x16" href="/favicon-16x16.png">
<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">
<link rel="manifest" href="/site.webmanifest">
<meta property="og:image" content="/og-image.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
"""
    snippet_path = output_dir / "head-tags.html"
    snippet_path.write_text(html_snippet, encoding="utf-8")
    created["head-tags.html"] = str(snippet_path)

    return created


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="new-web-icon-bundle",
        description=__doc__.splitlines()[0],
        epilog=EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("input", help="Source master image or SVG.")
    parser.add_argument("-o", "--output-dir", default="./web-icons", help="Output directory (default: ./web-icons).")
    parser.add_argument("--app-name", default="Web App", help="Application name for site.webmanifest.")
    parser.add_argument("--og-bg", default="#0F172A", help="Background hex color for 1200x630 og-image.png.")
    return parser


def main(argv: list[str]) -> int:
    parser = build_parser()
    args = parser.parse_args(normalize_help_argv(argv))
    in_path = Path(args.input).resolve()
    out_dir = Path(args.output_dir).resolve()

    if not in_path.exists():
        print(f"Error: Input file not found: {in_path}", file=sys.stderr)
        return 1

    res = generate_web_bundle(in_path, out_dir, app_name=args.app_name, og_bg=args.og_bg)
    print(f"=== Generated {len(res)} Web Bundle Assets in {out_dir} ===")
    for name, path in res.items():
        print(f"  * {name:22s} -> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
